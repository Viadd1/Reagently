<?php

/*
Creates a new user account using information submitted from register.php. The password is checked and hashed before the user is added to the database.
*/

// Include database connection
include 'db.php';


// Fetch data submitted from register.php

$username =
    $_POST['username'];

$firstname =
    $_POST['firstname'];

$lastname =
    $_POST['lastname'];

$lab =
    $_POST['lab'];

$email =
    $_POST['email'];

$password =
    $_POST['password'];

$confirm_password =
    $_POST['confirm_password'];


// Check whether the two entered passwords match
if ($password !== $confirm_password) {

    die(
        "Passwords do not match."
    );
}


// Hash the password before storing it in the database
// The original password should never be stored directly

$hashed_password =
    password_hash(
        $password,
        PASSWORD_DEFAULT
    );


// SQL statement
// role is not included here because the database
// automatically assigns the default value 'user'.
// user_id is also not included because it is AUTO_INCREMENT.
// created_at is automatically generated by MySQL.

$sql =
"INSERT INTO users
(
    username,
    firstname,
    lastname,
    lab,
    email,
    password
)

VALUES (?, ?, ?, ?, ?, ?)";


// Prepare SQL statement

$stmt =
    $link->prepare($sql);


$stmt->bind_param(
    "ssssss",
    $username,
    $firstname,
    $lastname,
    $lab,
    $email,
    $hashed_password
);


// Execute the INSERT statement

$result =
    $stmt->execute();


// Check whether registration was successful

if ($result) {

    echo "Registration successful.";

    echo '<br><br>';

    echo '<a href="login.php">
          Go to login
          </a>';

    echo '<br>';

    echo '<a href="index.php">
          Back to home
          </a>';

} else {

    // Display database error
    // For example, this may happen when an email address
    // already exists because email is UNIQUE.

    echo "Error: " .
         $stmt->error;
}


// Close prepared statement

$stmt->close();


// Close database connection

$link->close();

?>